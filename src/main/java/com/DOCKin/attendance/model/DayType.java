package com.DOCKin.attendance.model;

/**
 * 근무일 캘린더의 날짜 구분.
 *
 * <p>캘린더는 <b>예외 등록부</b>다. 등록되지 않은 날은 기본 규칙(평일=근무, 주말=휴무)을 따르고,
 * 등록된 날만 그 규칙을 덮어쓴다. 그래서 양방향 예외를 모두 표현할 수 있어야 한다 —
 * 평일인데 쉬는 날(공휴일)과 주말인데 일하는 날(특근)이 둘 다 존재한다.
 */
public enum DayType {
    /** 근무일. 주말에 등록하면 특근일이 된다. */
    WORKDAY,
    /** 주말. 기본 규칙과 같지만 명시적으로 등록해 둘 수 있다. */
    WEEKEND,
    /** 법정공휴일. 대체공휴일·임시공휴일 포함. */
    HOLIDAY,
    /** 회사 휴무일. 창립기념일, 하계휴가 등 법정공휴일이 아닌 휴무. */
    COMPANY_HOLIDAY
}

package com.DOCKin.rag.model;

/**
 * 청크의 공개 범위. 검색 단계에서 권한 필터로 사용한다.
 *
 * <p>벡터 유사도만으로는 접근 제어를 할 수 없으므로, 검색 결과를 그대로 챗봇 프롬프트에 넣으면
 * 권한 없는 사용자에게 남의 작업일지 내용이 노출된다. 이 값이 그 방어선이다.
 */
public enum Visibility {
    /** 전체 공개 (안전교육, 체크리스트, 향후 사내 규정) */
    PUBLIC,
    /** 작성자 본인과 ADMIN만 조회 가능 (작업일지) */
    OWNER
}
